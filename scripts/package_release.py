#!/usr/bin/env python3
"""Export minimal, rebuildable public source and a standalone static site; never publish."""
from pathlib import Path
import hashlib,json,shutil,subprocess,sys,tempfile,zipfile

ROOT=Path(__file__).resolve().parents[1]
TOP=['README.md','CONTRIBUTING.md','CONTRIBUTING.zh-CN.md','LICENSE','LICENSE-CODE','LICENSE-CONTENT','NOTICE.md','.gitignore','references.bib','implementation-references.bib']
DOCS=['methodology.md','methodology.zh-CN.md','taxonomy.md','taxonomy.zh-CN.md','pending-references.md','pending-references.zh-CN.md','acknowledgements.md','curation-update-2026-11-07.md','date-audit-2026-11-07.md','deployment.md','deployment.zh-CN.md']
SCRIPTS=['build.py','build_taxonomy_art.py','robot_art.py','validate.py','check_site.py','package_release.py']
ASSETS=['memory-map.svg','memory-robot.svg','link-paper.svg','link-code.svg','link-web.svg','neural-brain-network.png']
SITE_ASSETS=['app.js','constellation.js','i18n.js','style.css','favicon.svg','galaxy.jpg']
VISUALS='''# Visual assets

The galaxy background and neural-network brain are decorative illustrations generated with the built-in image tool. They are not astronomical observations, brain measurements or citation graphs. The runtime files are website/assets/galaxy.jpg and website/assets/neural-brain-network.png; the maintained brain source is assets/neural-brain-network.png.

The README taxonomy map is a self-contained original SVG generated by scripts/build_taxonomy_art.py. Its four quadrants use canonical domain and method data. The central robot is an original line-art vector from scripts/robot_art.py, matching the website header icon: a rounded face, antenna, side panels, pill-shaped eyes and a curved smile. No third-party reference image is bundled.

Interactive stars represent research domains and method families. Decorative positions do not encode quality, similarity or performance. Hovering or keyboard-focusing a domain lights both that domain and the central memory emblem. The pause control and reduced-motion preference apply to the animated starfield and neural signals.

The Chinese headline is “每一个动作，皆有迹可循。” The English headline remains “Every action has a past.” [StepFun](https://www.stepfun.com/) informed the scroll-linked presentation; its code and imagery were not copied.

Project artwork is covered by the content license; see [NOTICE](../NOTICE.md).
'''

def copy(source,target):
    target.parent.mkdir(parents=True,exist_ok=True)
    shutil.copy2(source,target)

def main():
    out=ROOT/'dist';out.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='release-',dir=out) as temp:
        stage=Path(temp)/'Awesome-Embodied-Memory';stage.mkdir()
        for name in TOP:copy(ROOT/name,stage/name)
        for name in DOCS:copy(ROOT/'docs'/name,stage/'docs'/name)
        for name in SCRIPTS:copy(ROOT/'scripts'/name,stage/'scripts'/name)
        for name in ASSETS:copy(ROOT/'assets'/name,stage/'assets'/name)
        for path in sorted((ROOT/'data').glob('*.json')):copy(path,stage/'data'/path.name)
        for path in sorted((ROOT/'.github').rglob('*')):
            if path.is_file() and path.suffix in ['.md','.yml','.yaml']:copy(path,stage/path.relative_to(ROOT))
        copy(ROOT/'website/index.html',stage/'website/index.html')
        for name in SITE_ASSETS:copy(ROOT/'website/assets'/name,stage/'website/assets'/name)
        (stage/'website/.nojekyll').write_text('')
        (stage/'docs/visual-assets.md').write_text(VISUALS,encoding='utf-8')
        for script in ['validate.py','build.py','check_site.py']:
            subprocess.run([sys.executable,str(stage/'scripts'/script)],cwd=stage,check=True)
        for path in stage.rglob('__pycache__'):shutil.rmtree(path)
        for path in stage.rglob('*'):
            assert not path.is_symlink(),f'Symlink in release: {path}'
            assert path.name not in ['.DS_Store','.env','AGENTS.md']
        source_dir=out/'Awesome-Embodied-Memory'
        website_dir=out/'Awesome-Embodied-Memory-website'
        # These paths are generated build artifacts inside the ignored dist directory.
        for path in [source_dir,website_dir]:
            if path.exists():shutil.rmtree(path)
        shutil.copytree(stage,source_dir)
        shutil.copytree(stage/'website',website_dir)
    manifest=[]
    for path in sorted(source_dir.rglob('*')):
        if path.is_file():manifest.append({'path':str(path.relative_to(source_dir)),'bytes':path.stat().st_size,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
    for directory,name,prefix in [(source_dir,'Awesome-Embodied-Memory-source.zip','Awesome-Embodied-Memory/'),(website_dir,'Awesome-Embodied-Memory-website.zip','')]:
        with zipfile.ZipFile(out/name,'w',zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(directory.rglob('*')):
                if path.is_file():archive.write(path,prefix+str(path.relative_to(directory)))
    (out/'release-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    names=['Awesome-Embodied-Memory-source.zip','Awesome-Embodied-Memory-website.zip','release-manifest.json']
    (out/'SHA256SUMS').write_text(''.join(hashlib.sha256((out/n).read_bytes()).hexdigest()+'  '+n+'\n' for n in names))
    print(json.dumps({'public_source_files':len(manifest),'source_directory':str(source_dir),'website_directory':str(website_dir),'source_zip_bytes':(out/names[0]).stat().st_size,'website_zip_bytes':(out/names[1]).stat().st_size}))

if __name__=='__main__':main()
